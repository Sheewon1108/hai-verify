const fs = require("fs");
const path = require("path");

const PROJECT_ROOT = path.join(__dirname, "..");
const QUESTIONS_DIR = path.join(PROJECT_ROOT, "hai-ic", "test-questions");
const OUT_DIR = path.join(PROJECT_ROOT, "hai-ic", "buyer-deliverables");

function readStepFiles() {
  if (!fs.existsSync(QUESTIONS_DIR)) return [];
  return fs
    .readdirSync(QUESTIONS_DIR)
    .filter((f) => /^step-\d+/.test(f) && f.endsWith(".json"))
    .sort()
    .map((f) => JSON.parse(fs.readFileSync(path.join(QUESTIONS_DIR, f), "utf8")));
}

function backupDeliverables() {
  const stamp = new Date().toISOString().slice(0, 10);
  const driveBases = [
    path.join(process.env.USERPROFILE || "", "OneDrive"),
    path.join(process.env.USERPROFILE || "", "Google Drive"),
    "G:\\My Drive",
  ];
  for (const base of driveBases) {
    if (base && fs.existsSync(base)) {
      const dest = path.join(base, "hai-ic-backups", "buyer-deliverables", stamp);
      fs.mkdirSync(dest, { recursive: true });
      for (const f of fs.readdirSync(OUT_DIR)) {
        fs.copyFileSync(path.join(OUT_DIR, f), path.join(dest, f));
      }
      return dest;
    }
  }
  return null;
}

function generate() {
  const steps = readStepFiles();
  const all = [];
  for (const s of steps) {
    for (const r of s.results || []) {
      all.push({ ...r, step: s.step, at: s.at });
    }
  }

  const total = all.length;
  const off = all.filter((r) => r.mode === "OFF");
  const on = all.filter((r) => r.mode === "ON");
  const dd = all.filter((r) => r.dd);
  const ddOff = dd.filter((r) => r.mode === "OFF");
  const avgIC =
    total > 0
      ? Math.round((all.reduce((a, r) => a + Number(r.ic), 0) / total) * 10) / 10
      : 0;

  fs.mkdirSync(OUT_DIR, { recursive: true });
  const today = new Date().toISOString().slice(0, 10);

  const ledger = `# Hai-Ic Trust Ledger — ${today}

**Owner:** KARAM SHIN  
**Product:** Intent Confidence Gate (진심일 때만 답함)

> 세상이 AI를 못 믿을 때, Hai-Ic는 **확실하지 않으면 답하지 않습니다.**

## Summary (auto-generated from live tests)

| Metric | Value |
|--------|-------|
| Questions analyzed | **${total}** |
| 진심 모드 ON (≥75%) | **${on.length}** (${total ? Math.round((on.length / total) * 100) : 0}%) |
| 진심 모드 OFF (<75%) | **${off.length}** (${total ? Math.round((off.length / total) * 100) : 0}%) |
| DD / 검증형 질문 | **${dd.length}** |
| DD 중 OFF (증거 요구 차단) | **${ddOff.length}** |
| Avg Intent Confidence | **${avgIC}%** |

## Buyer value (why this matters)

1. **OFF = 리스크 차단** — 불확실할 때 hallucination·과장 답변을 막음  
2. **ON = 진심 답변 허가** — confidence gate 통과한 것만 full answer  
3. **감사 추적** — 모든 판단이 로그·백업됨 (연습 일지 → **신뢰 원장**)

## Live demo

Scheduled on a 30-minute call — live walkthrough on your use case (no public URL until POC).

---
*Generated by hai-ic automation — scores not manually raised*
`;

  const offCases = off
    .slice(0, 15)
    .map(
      (r, i) =>
        `### ${i + 1}. IC ${r.ic}% — OFF\n- **질문:** ${r.question}\n- **DD:** ${r.dd ? "Yes" : "No"}\n- **의미:** buyer에게 억지 답 대신 clarifying / evidence 요청\n`,
    )
    .join("\n");

  const offDoc = `# Hai-Ic — OFF 케이스 (억지 답변 안 한 순간)

**${today}** · 총 ${off.length}건 중 상위 샘플

${offCases || "_아직 OFF 케이스 없음 — 더 많은 질문 수집 중_"}

---
**Pitch 한 줄:** "우리 AI는 모를 때 입을 닫습니다. 그게 진정성입니다."
`;

  const cert = {
    product: "hai-ic",
    owner: "KARAM SHIN",
    type: "Sincerity Certificate (sample)",
    generatedAt: new Date().toISOString(),
    description:
      "API 응답마다 Intent Confidence % + 진심모드 ON/OFF 스탬프 — SSL for AI sincerity",
    sample: on[0]
      ? {
          question: on[0].question,
          intentConfidence: on[0].ic,
          sincereMode: on[0].mode,
          passed: on[0].mode === "ON",
          stamp: `HAI-IC-SINCERE-${on[0].ic}`,
        }
      : null,
    ofSample: off[0]
      ? {
          question: off[0].question,
          intentConfidence: off[0].ic,
          sincereMode: "OFF",
          action: "clarifying_questions_required",
          stamp: `HAI-IC-HOLD-${off[0].ic}`,
        }
      : null,
  };

  const mistrust = `# AI Mistrust Index — ${today}

**Thesis:** 지금 세상은 AI를 못 믿는다. Hai-Ic는 그 **불신을 제품화**한다.

| Signal | Data |
|--------|------|
| 검증/DD형 질문 비율 | **${total ? Math.round((dd.length / total) * 100) : 0}%** |
| buyer가 증거 요구하는 패턴 | latency, ROI, licensing, compliance |
| Hai-Ic 대응 | OFF → evidence first, ON → sincere answer |

## Timing

- Enterprise: "Show me before you answer"
- Regulators: AI act, liability
- **Hai-Ic position:** Pre-LLM **Intent Confidence Gate**

## Targets

1. Growth Loops — multi-agent 앞단 gate  
2. instinctools — SDK + Sincerity Certificate  
3. Closeloop — workflow 첫 단계 risk filter  

---
*Auto-updated weekly by hai-ic automation*
`;

  const pitchOnePager = `# Hai-Ic — Buyer One-Pager (${today})

**한 줄:** AI가 **모를 때 답 안 하는** gate. 진심일 때만 진심으로.

| | Without Hai-Ic | With Hai-Ic |
|---|----------------|-------------|
| 불확실한 질문 | LLM이 그럴듯하게 답 → hallucination risk | **OFF** → clarifying / evidence |
| DD / 실사 | 과장·수치 날조 위험 | **${ddOff.length}/${dd.length}** DD 질문 차단 샘플 |
| 감사 | 없음 | Trust Ledger 백업 |

**Ask:** 2주 POC · $8.5k–$25k/yr license  
**Demo:** 30-min live call (your stack / use case)
**Contact:** KARAM SHIN

---
*Data: ${total} real questions · avg IC ${avgIC}% · scores not manually raised*
`;

  fs.writeFileSync(path.join(OUT_DIR, "TRUST-LEDGER.md"), ledger, "utf8");
  fs.writeFileSync(path.join(OUT_DIR, "OFF-CASES.md"), offDoc, "utf8");
  fs.writeFileSync(
    path.join(OUT_DIR, "SINCERITY-CERTIFICATE-sample.json"),
    JSON.stringify(cert, null, 2) + "\n",
    "utf8",
  );
  fs.writeFileSync(path.join(OUT_DIR, "MISTRUST-INDEX.md"), mistrust, "utf8");
  fs.writeFileSync(path.join(OUT_DIR, "BUYER-ONE-PAGER.md"), pitchOnePager, "utf8");

  const backupDest = backupDeliverables();
  return { total, off: off.length, on: on.length, outDir: OUT_DIR, backupDest };
}

if (require.main === module) {
  const r = generate();
  console.log(
    `[buyer-trust-pack] ${r.total} questions → OFF ${r.off} ON ${r.on} → ${r.outDir}`,
  );
  if (r.backupDest) console.log(`[buyer-trust-pack] backup: ${r.backupDest}`);
}

module.exports = { generate };